export const calculateDiagnosisResult = (
  answers: { [key: string]: number },
  industryId: string,
  industryName: string,
  selectedGakuchika: string[] = [],
  gakuchikaDetail: string = "",
  selectedCareerGoals: string[] = []
): { result: DiagnosisResult; initialData: SelfAnalysisData } => {
  const eOrI = answers.E >= answers.I ? "E" : "I";
  const sOrN = answers.S >= answers.N ? "S" : "N";
  const tOrF = answers.T >= answers.F ? "T" : "F";
  const jOrP = answers.J >= answers.P ? "J" : "P";

  const typeCode = `${eOrI}${sOrN}${tOrF}${jOrP}`;

  const detail = typeDetailsMap[typeCode] || {
    name: `${typeCode}タイプ・バランス型キャリア人`,
    role: "総合職・企画営業・プロジェクト推進",
    advice: "柔軟な対応力とバランスの良さがあなたの最大の武器です。多様な視点を持ちながら着実に成果を上げることができます。",
    esTip: "具体的な実績とチームでの役割をアピールし、自身の強みがどのように組織に貢献できるかを論理的に伝えましょう。"
  };

  const diagnosisResult: DiagnosisResult = {
    typeCode,
    typeName: detail.name,
    recommendedRole: detail.role,
    advice: detail.advice,
    esTip: detail.esTip,
  };

  // ガクチカの文章組み立て
  let experienceCore = "";
  if (gakuchikaDetail) {
    experienceCore = `${gakuchikaDetail}に関する取り組み`;
  } else if (selectedGakuchika.length > 0) {
    experienceCore = selectedGakuchika.join("や") + "の活動";
  } else {
    experienceCore = "学生時代の様々な挑戦";
  }

  // 将来ビジョンの文章組み立て
  const careerGoalText = selectedCareerGoals.length > 0
    ? selectedCareerGoals.join("、および") + "を実現したいと考えています。"
    : "自身の専門性を高め、組織の成長と新しい価値の創造に貢献したいと考えています。";

  const initialData: SelfAnalysisData = {
    motivation: `${industryName}業界を志望する理由は、私の価値観と貴社の事業領域が深く合致しているためです。${detail.name}としての特性である「${detail.role}」の視点を活かし、チームの目標達成と事業成長に貢献したいと考え、志望いたしました。`,
    strengths: `私の強みは、${detail.name}としての強みを活かした粘り強い課題解決力です。状況を客観的に分析し、周囲と協力しながら最適なアプローチを実行することができます。`,
    experiences: `学生時代に最も力を入れたことは、${experienceCore}です。直面した困難や課題に対しても、${detail.name}の長所である主体性と実行力を発揮し、周囲と連携しながら乗り越えました。`,
    careerGoal: `入社後は、${industryName}の領域において${careerGoalText}`,
  };

  return {
    result: diagnosisResult,
    initialData,
  };
};